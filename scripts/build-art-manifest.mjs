// Scans assets/ and writes js/artmanifest.jsx.
//
// Without this the portrait component guesses a filename and asks for it, which
// means a 404 in the console for every breed that has no art yet - noisy for a
// player, and an automatic build failure here, since the smoke test treats any
// console error as a break. Asking only for files that exist is also just less
// wasteful than firing thirty requests to miss twenty-five of them.
//
// Re-run after dropping new art in. `npm run art:manifest`.
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ASSETS = path.join(ROOT, "assets");
const WATCHED = ["dogs", "horses", "cattle", "patterns"];

const found = [];
for (const dir of WATCHED) {
  const full = path.join(ASSETS, dir);
  if (!fs.existsSync(full)) continue;
  for (const f of fs.readdirSync(full)) {
    if (/\.(png|jpg|jpeg|webp)$/i.test(f)) found.push(`${dir}/${f}`);
  }
}
found.sort();

const body = `/* Generated by scripts/build-art-manifest.mjs - do not edit by hand.

   Which art files actually exist in assets/. The portrait component checks this
   before requesting anything, so a breed without art falls straight back to the
   generated swatch instead of firing a request that 404s.

   ${found.length} file${found.length === 1 ? "" : "s"} at last build. Re-run
   \`npm run art:manifest\` after adding more. */
const ART_MANIFEST = new Set(${JSON.stringify(found, null, 2).replace(/\n/g, "\n  ")});
function hasArt(rel) { return ART_MANIFEST.has(rel); }
`;

fs.writeFileSync(path.join(ROOT, "js", "artmanifest.jsx"), body);
console.log(`js/artmanifest.jsx - ${found.length} art file(s)`);
for (const f of found) console.log("  " + f);
